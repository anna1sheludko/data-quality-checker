"""Reporter: Markdown."""
from src.report.base import BaseReporter


SEVERITY_EMOJI = {
    "ok": "✅",
    "info": "ℹ️",
    "warning": "⚠️",
    "critical": "🔴",
}


class MarkdownReporter(BaseReporter):

    def render(self) -> str:
        ctx = self.context
        lines = []

        # Header
        lines.append(f"# Data Quality Report — {ctx.source_name}")
        lines.append("")
        lines.append(f"**Generated:** {ctx.generated_at.strftime('%Y-%m-%d %H:%M:%S')}")
        lines.append(f"**Source:** `{ctx.source_file}` ({ctx.file_format})")
        lines.append(f"**Rows:** {ctx.total_rows:,}  |  **Columns:** {ctx.total_columns}")
        lines.append("")

        # Overall
        emoji = SEVERITY_EMOJI.get(ctx.overall_severity, "")
        lines.append(f"## Overall: {emoji} {ctx.overall_severity.upper()}")
        lines.append("")
        lines.append(f"- **Total issues:** {ctx.total_issues}")
        lines.append(f"- 🔴 Critical: {ctx.total_critical}")
        lines.append(f"- ⚠️ Warnings: {ctx.total_warnings}")
        lines.append(f"- ℹ️ Info: {ctx.total_info}")
        lines.append("")

        # Summary table of checks
        lines.append("## Checks overview")
        lines.append("")
        lines.append("| Check | Status | Severity | Issues |")
        lines.append("|---|---|---|---|")
        for r in ctx.results:
            status = "✅ passed" if r.passed else "❌ failed"
            emoji = SEVERITY_EMOJI.get(r.severity.value, "")
            lines.append(f"| {r.name} | {status} | {emoji} {r.severity.value} | {len(r.issues)} |")
        lines.append("")

        # Detailed per-check
        lines.append("## Details")
        lines.append("")

        for r in ctx.results:
            lines.append(f"### {r.name}")
            lines.append("")
            lines.append(f"*{r.message}*")
            lines.append("")

            if not r.issues:
                lines.append("No issues found.")
                lines.append("")
                continue

            for issue in r.issues:
                emoji = SEVERITY_EMOJI.get(issue.severity.value, "")
                col_part = f" `[{issue.column}]`" if issue.column else ""
                lines.append(f"- {emoji} **{issue.severity.value}**{col_part} — {issue.message}")
            lines.append("")

        # Footer
        lines.append("---")
        lines.append("")
        lines.append("*Generated by Data Quality Checker*")
        lines.append("")

        return "\n".join(lines)